import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { writeFileSync } from "node:fs";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const desktop = resolve(scriptDirectory, "..");
const metadata = JSON.parse(execFileSync("cargo", [
  "metadata",
  "--locked",
  "--manifest-path",
  resolve(desktop, "Cargo.toml"),
  "--format-version",
  "1",
], {
  cwd: desktop,
  encoding: "utf8",
  maxBuffer: 128 * 1024 * 1024,
}));

const packages = new Map(metadata.packages.map((pkg) => [pkg.id, pkg]));
const nodes = new Map(metadata.resolve.nodes.map((node) => [node.id, node]));
const depths = new Map(metadata.workspace_members.map((id) => [id, 0]));
const queue = [...metadata.workspace_members];
const compareText = (left, right) => (left === right ? 0 : left < right ? -1 : 1);

for (let index = 0; index < queue.length; index += 1) {
  const id = queue[index];
  const depth = depths.get(id);
  for (const dependency of nodes.get(id)?.dependencies ?? []) {
    if (!depths.has(dependency)) {
      depths.set(dependency, depth + 1);
      queue.push(dependency);
    }
  }
}

const rows = [...depths.entries()]
  .map(([id, depth]) => {
    const pkg = packages.get(id);
    if (!pkg) throw new Error(`metadata package missing for ${id}`);
    const license = pkg.license ?? (pkg.license_file ? `license-file: ${pkg.license_file}` : null);
    const source = pkg.source ?? "workspace path";
    return {
      depth,
      direct: depth === 0 ? "workspace member" : "transitive",
      name: pkg.name,
      version: pkg.version,
      source,
      license: license ?? (pkg.source ? "UNSPECIFIED — review required" : "PROJECT-OWNED — repository policy"),
    };
  })
  .sort((left, right) => compareText(left.name, right.name) || compareText(left.version, right.version) || compareText(left.source, right.source));

const escapeCell = (value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
const lines = [
  "# R3B Application Cargo License Report",
  "",
  "> Generated from the locked application Cargo graph; do not edit manually.",
  "",
  `- Generated by: \`node scripts/generate-cargo-license-report.mjs\``,
  `- Source: \`apps/desktop/Cargo.lock\` plus \`cargo metadata --locked --manifest-path apps/desktop/Cargo.toml --format-version 1\``,
  `- Workspace members: ${metadata.workspace_members.length}`,
  `- Reachable packages: ${rows.length}`,
  "- License values are the package metadata values resolved by Cargo. Workspace-owned packages are identified explicitly; any third-party `UNSPECIFIED` entry requires legal review before adoption.",
  "",
  "| Depth | Reachability | Package | Version | License / policy | Source |",
  "|---:|---|---|---|---|---|",
  ...rows.map((row) => `| ${row.depth} | ${row.direct} | ${escapeCell(row.name)} | ${escapeCell(row.version)} | ${escapeCell(row.license)} | ${escapeCell(row.source)} |`),
];

writeFileSync(resolve(desktop, "CARGO_LICENSE_REPORT.md"), `${lines.join("\n")}\n`);
console.log(`Wrote ${rows.length} package license rows to CARGO_LICENSE_REPORT.md`);
